-- 34 baris: 29 leaf + 5 parent (3, 4, 5, 7, 8).
-- Total per grup dihitung saat render (tidak disimpan).

CREATE TABLE IF NOT EXISTS sirs_rl36_entry (
  id              INT AUTO_INCREMENT PRIMARY KEY,
  bulan           CHAR(7) NOT NULL,
  urutan          DECIMAL(5,1) NOT NULL,
  jenis_kode      VARCHAR(10) NOT NULL,
  jenis_nama      VARCHAR(180) NOT NULL,
  parent_kode     VARCHAR(10) NULL,
  is_parent       TINYINT(1) NOT NULL DEFAULT 0,
  rm_rs           INT,
  rm_bidan        INT,
  rm_puskes       INT,
  rm_faskes_lain  INT,
  rm_hidup        INT,
  rm_mati         INT,
  rnm_hidup       INT,
  rnm_mati        INT,
  nr_hidup        INT,
  nr_mati         INT,
  dirujuk         INT,
  updated_at      DATETIME,
  updated_by      VARCHAR(20),
  UNIQUE KEY uniq_bulan_jenis (bulan, jenis_kode),
  KEY idx_bulan (bulan)
);

